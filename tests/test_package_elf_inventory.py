import importlib.util
import sys
import unittest
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1] / 'scripts'
sys.path.insert(0, str(SCRIPTS))
SPEC = importlib.util.spec_from_file_location('package_elf_inventory',
                                             SCRIPTS / 'probe_package_elf_inventory.py')
inventory = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(inventory)


class ElfInventoryParserTests(unittest.TestCase):
    def test_dynamic_names_preserve_order_soname_and_search_paths(self):
        result = inventory.dynamic_names('''
 0x0000000000000001 (NEEDED) Shared library: [libc.so.6]
 0x0000000000000001 (NEEDED) Shared library: [libssl.so.3]
 0x000000000000000e (SONAME) Library soname: [libexample.so.1]
 0x000000000000000f (RPATH) Library rpath: [$ORIGIN/../lib:/opt/fixed]
 0x000000000000001d (RUNPATH) Library runpath: [/usr/lib/example]
 0x0000000000000000 (NULL) 0x0
''')
        self.assertEqual(result, dict(needed=['libc.so.6', 'libssl.so.3'],
            soname=['libexample.so.1'], rpath=['$ORIGIN/../lib:/opt/fixed'],
            runpath=['/usr/lib/example']))

    def test_missing_dynamic_section_does_not_invent_dependencies(self):
        self.assertEqual(inventory.dynamic_names('There is no dynamic section.'),
                         dict(needed=[], soname=[], rpath=[], runpath=[]))

    def test_malformed_recognized_dynamic_tag_is_rejected(self):
        for line in ('0x1 (NEEDED) Shared library: libc.so.6',
                     '0x1 (NEEDED) Shared library: []',
                     '0x1 (NEEDED) Shared library: [lib.so] trailing'):
            with self.subTest(line=line), self.assertRaises(ValueError):
                inventory.dynamic_names(line)

    def test_duplicate_singleton_is_rejected_but_repeated_needed_is_preserved(self):
        with self.assertRaises(ValueError):
            inventory.dynamic_names('(SONAME) [first]\n(SONAME) [second]')
        self.assertEqual(inventory.dynamic_names('(NEEDED) [x]\n(NEEDED) [x]')['needed'],
                         ['x', 'x'])

    def test_cache_keeps_all_candidates_without_claiming_loader_selection(self):
        result = inventory.cache_entries('''
2 libs found in cache `/etc/ld.so.cache'
 libfoo.so.1 (libc6,x86-64) => /lib/x86_64-linux-gnu/libfoo.so.1
 libfoo.so.1 (libc6,x86-64, hwcap: 0x0002) => /lib/glibc-hwcaps/x86-64-v3/libfoo.so.1
Cache generated by: ldconfig
''')
        self.assertEqual(result, {'libfoo.so.1': [
            '/lib/glibc-hwcaps/x86-64-v3/libfoo.so.1', '/lib/x86_64-linux-gnu/libfoo.so.1']})

    def test_cache_deduplicates_repeated_entry(self):
        self.assertEqual(inventory.cache_entries('libx (libc6) => /lib/x\n' * 2),
                         {'libx': ['/lib/x']})

    def test_cache_rejects_unparseable_or_relative_candidates(self):
        for line in ('libx => /lib/x', 'libx (libc6) => relative',
                     'libx (libc6) => /lib/name with spaces'):
            with self.subTest(line=line), self.assertRaises(ValueError):
                inventory.cache_entries(line)
