"""Bound fresh-cache witnesses and compare logical data; never admit mutations."""
import base64
import hashlib
import json

from mano_runtime.package_gdbm_decode import decode
from mano_runtime.package_man_cache import MAX_DATABASE_BYTES, index_path

MAX_DATABASES = 64
MAX_TOTAL_BYTES = 8 * 1024**2
MAX_TOTAL_RECORDS = 65536
MAX_SERIALIZED = 16 * 1024**2


def canonical(value):
    return json.dumps(value, sort_keys=True, allow_nan=False).encode()


def inputs(baseline, candidate, config):
    row = baseline['entries']['etc/manpath.config']
    if (row['kind'] != 'file' or row['uid'] != 0 or row['mode'] & 0o022
            or type(config) is not bytes or not 0 < len(config) <= 65536
            or row['bytes'] != len(config)
            or row['sha256'] != hashlib.sha256(config).hexdigest()):
        raise ValueError('Exact immutable baseline manpath configuration required')
    pages = {path: row for path, row in candidate['entries'].items()
             if path == 'usr/share/man' or path.startswith('usr/share/man/')}
    if not pages or pages.get('usr/share/man', {}).get('kind') != 'directory':
        raise ValueError('Observed candidate manual-page tree required')
    return dict(baseline_sha256=baseline['manifest_sha256'],
                candidate_sha256=candidate['manifest_sha256'],
                candidate_manual_tree_sha256=hashlib.sha256(canonical(pages)).hexdigest(),
                candidate_manual_tree_entries=len(pages), config_sha256=row['sha256'],
                command=['/usr/bin/mandb', '--create', '--quiet', '/usr/share/man'],
                trusted_runtime_closure_verified=False, source_authority_verified=False)


def collect(tree, read):
    """Keep raw databases in one bounded JSON artifact, not 64 extra tar paths."""
    paths = sorted(path for path in tree['entries'] if index_path('var/cache/man/' + path))
    if not paths or len(paths) > MAX_DATABASES:
        raise ValueError('Bounded nonempty regenerated database set required')
    files, total = {}, 0
    for path in paths:
        row = tree['entries'][path]
        if (row['kind'] != 'file' or any(type(row[k]) is not int for k in
                ('uid', 'gid', 'mode', 'nlink', 'bytes'))
                or (row['uid'], row['gid'], row['mode'], row['nlink']) != (6, 12, 0o644, 1)
                or row['xattrs'] != {} or row['hardlink_anchor'] != path
                or not 0 <= row['bytes'] <= MAX_DATABASE_BYTES
                or total + row['bytes'] > MAX_TOTAL_BYTES):
            raise ValueError('Bounded plain regenerated database required')
        data = read(path, MAX_DATABASE_BYTES)
        if (type(data) is not bytes or len(data) != row['bytes']
                or hashlib.sha256(data).hexdigest() != row['sha256']):
            raise ValueError('Regenerated bytes differ from drained tree')
        files[path] = base64.b64encode(data).decode('ascii')
        total += len(data)
    encoded = canonical(files)
    if len(encoded) > MAX_SERIALIZED:
        raise ValueError('Regenerated raw bundle serialization budget')
    return dict(databases=len(files), bytes=total, artifact='staged-man-regenerated-bytes.json',
                artifact_bytes=len(encoded), sha256=hashlib.sha256(encoded).hexdigest(),
                tree_sha256=tree['manifest_sha256']), encoded


def compare(raw_bundle, candidate_files):
    """Compare exact key/value pairs, without treating physical DB slack as valid."""
    if (type(raw_bundle) is not bytes or len(raw_bundle) > MAX_SERIALIZED
            or type(candidate_files) is not dict or len(candidate_files) > 8):
        raise ValueError('Bounded regeneration comparison inputs required')
    files = json.loads(raw_bundle)
    if type(files) is not dict or not 1 <= len(files) <= MAX_DATABASES:
        raise ValueError('Bounded regenerated database map required')
    total, records = 0, 0

    def logical(raw):
        nonlocal total, records
        if type(raw) is not bytes or len(raw) > MAX_DATABASE_BYTES:
            raise ValueError('Bounded database bytes required')
        total += len(raw)
        if total > MAX_TOTAL_BYTES * 2:
            raise ValueError('Regeneration comparison byte budget')
        report = decode(raw)
        records += report['decoded_records']
        if records > MAX_TOTAL_RECORDS:
            raise ValueError('Regeneration comparison record budget')
        return {r['key_base64']: r['value_base64'] for r in report['records']}

    regenerated = {}
    for path, encoded in sorted(files.items()):
        if (not isinstance(path, str) or not index_path('var/cache/man/' + path)
                or type(encoded) is not str or len(encoded) > 4 * (MAX_DATABASE_BYTES + 2) // 3):
            raise ValueError('Fixed bounded regenerated cache entry required')
        regenerated['var/cache/man/' + path] = logical(base64.b64decode(encoded, validate=True))
    rows = {}
    for path, data in sorted(candidate_files.items()):
        if not index_path(path):
            raise ValueError('Fixed candidate man-index path required')
        candidate = logical(data)
        fresh = regenerated.get(path)
        rows[path] = (dict(regenerated_index_present=False, logical_records_equal=False)
                      if fresh is None else dict(regenerated_index_present=True,
            logical_records_equal=candidate == fresh,
            candidate_records=len(candidate), regenerated_records=len(fresh),
            candidate_only_keys=sorted(candidate.keys() - fresh.keys()),
            regenerated_only_keys=sorted(fresh.keys() - candidate.keys()),
            differing_value_keys=sorted(key for key in candidate.keys() & fresh.keys()
                                        if candidate[key] != fresh[key])))
    result = dict(profile='fresh-man-index-logical-comparison-v1', databases=rows,
                  regenerated_databases=len(regenerated), decoded_records=records,
                  all_compared_indexes_equal=bool(rows) and all(
                      row['logical_records_equal'] for row in rows.values()),
                  all_database_bytes_validated=False, cache_sources_verified=False,
                  generated_state_validated=False, changes_authorized=False,
                  publication_authorized=False)
    if len(canonical(result)) > MAX_SERIALIZED:
        raise ValueError('Regeneration comparison output budget')
    return result


def compare_policy_pair(control_bundle, restricted_bundle):
    """Require every logical index to survive confinement, including unchanged ones.

    Physical allocation, unused blocks and timestamps may differ between runs.
    Both complete active-record maps must agree; neither run gains authority.
    """
    total_bytes, total_records = 0, 0

    def pairs(items):
        result = {}
        for key, value in items:
            if key in result:
                raise ValueError('Duplicate cache bundle path')
            result[key] = value
        return result

    def load(bundle):
        nonlocal total_bytes, total_records
        if type(bundle) is not bytes or len(bundle) > MAX_SERIALIZED:
            raise ValueError('Bounded cache policy comparison required')
        files = json.loads(bundle, object_pairs_hook=pairs)
        if type(files) is not dict or not 1 <= len(files) <= MAX_DATABASES:
            raise ValueError('Bounded complete cache map required')
        result = {}
        for path, encoded in sorted(files.items()):
            if (type(path) is not str or not index_path('var/cache/man/' + path)
                    or type(encoded) is not str
                    or len(encoded) > 4 * (MAX_DATABASE_BYTES + 2) // 3):
                raise ValueError('Fixed cache path and bounded bytes required')
            raw = base64.b64decode(encoded, validate=True)
            if len(raw) > MAX_DATABASE_BYTES:
                raise ValueError('Cache database byte budget')
            total_bytes += len(raw)
            if total_bytes > 2 * MAX_TOTAL_BYTES:
                raise ValueError('Cache pair aggregate byte budget')
            decoded = decode(raw)
            total_records += decoded['decoded_records']
            if total_records > 2 * MAX_TOTAL_RECORDS:
                raise ValueError('Cache pair aggregate record budget')
            result[path] = {row['key_base64']: row['value_base64']
                            for row in decoded['records']}
        return result

    control, restricted = load(control_bundle), load(restricted_bundle)
    if control != restricted:
        raise ValueError('Input restrictions changed the complete logical cache output')
    return dict(profile='man-cache-input-policy-pair-v1',
                control_sha256=hashlib.sha256(control_bundle).hexdigest(),
                restricted_sha256=hashlib.sha256(restricted_bundle).hexdigest(),
                databases=len(control), records=sum(map(len, control.values())),
                all_index_paths_equal=True, all_logical_records_equal=True,
                cache_sources_verified=False, generated_state_validated=False,
                changes_authorized=False, publication_authorized=False)
